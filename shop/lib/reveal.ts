// =========================================================================
// Разметка узла, который показывает слой движения.
//
// Слой пишет инлайновый style по прямоугольнику и успевает дойти до узла до
// того, как React догидратирует отложенную границу (панель каталога на главной).
// React 19 сверяет DOM-атрибуты с пропами и печатает «A tree hydrated but some
// attributes … didn't match»: чужой атрибут для него — расхождение server/client.
// suppressHydrationWarning — штатный ответ на «этот DOM трогает не React»: он
// снимает сверку атрибутов самого узла, детей не затрагивает, поэтому настоящая
// ошибка в тексте карточки всё равно останется видимой.
// =========================================================================

export const revealProps = { 'data-reveal': true, suppressHydrationWarning: true } as const;

/**
 * Появление конкретным ключом: 'mask' — заголовок срезают слева, 'clip' — фотография
 * выезжает из-под нижнего края. Вариант стоит в разметке, а не в слое: слой знает только
 * геометрически, что узел попал в кадр, а чем именно он показан — решение страницы.
 * Имя превращается в `--reveal-name` одним местом (components/Motion.tsx), поэтому
 * `nh-<вариант>` обязан существовать в globals.css — иначе узел навсегда останется
 * обрезанным, и это ловит гейт по ключевым кадрам.
 */
export function revealInto(into: 'mask' | 'clip') {
  return { 'data-reveal': true, 'data-reveal-into': into, suppressHydrationWarning: true } as const;
}
