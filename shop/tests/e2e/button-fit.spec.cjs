// «Некоторые кнопки кривые, и слова в них выходят за рамку» — так это видит покупатель,
// и ни один прежний гейт этого не мерил. storefront сравнивает computed-стили
// представителей (.btn-primary/.add-btn/.form-input) и ширину страницы: у кнопки с
// правильными токенами подпись всё равно ложится встык к рамке или вылезает за неё,
// потому что считать нужно не стиль, а реальные глифы внутри конкретной кнопки.
//
// Проверяется на обеих витринах, на проектных 1440/768/360 и дополнительно на 320,
// в раскрытых слоях (шторка корзины, оформление, плеер историй, панель связи):
//   1. текст не касается рамки и не выходит за неё — с четырёх сторон;
//   2. текст не обрезан (scrollWidth/scrollHeight против клиентских размеров);
//   3. контрол не шире своего места, если место не прокручивается полосой;
//   4. контролы одного визуального ряда одинаковой высоты.
//
// Два уточнения, без которых замер врал бы на ровной вёрстке:
//   · ряд = общий предок И перекрытие по вертикали больше половины высоты. Кнопки,
//     лежащие друг под другом, — не ряд, сверять их высоты нельзя; вне потока (fixed,
//     absolute) контролы в ряд не входят вовсе;
//   · полоса с горизонтальным скроллом (лента историй, вкладки отделов) по замыслу
//     шире экрана, поэтому «кнопка шире контейнера» внутри неё — не дефект.
// Две строки в подписи сами по себе не дефект: дефект — текст, прижатый к рамке.

const ВРЕЗКА = 4; // меньше 4px от глифов до рамки — слова липнут к краю
const РАЗРЯД = 1; // субпиксельная раскладка
const РАЗБРОС = 2; // предельная разница высот в ряду
const УЗКАЯ = { width: 320, height: 640 }; // самая тесная ширина, на которой вёрстка трещит

const ЗАМЕР = () => {
  const этоКонтрол = (узел) => {
    if (!узел || !узел.tagName || !узел.getBoundingClientRect) return false;
    const класс = typeof узел.className === 'string' ? узел.className : String((узел.className && узел.className.baseVal) || '');
    return узел.tagName === 'BUTTON' || узел.getAttribute('role') === 'button' || /(^|[\s-])(btn|button)/.test(класс);
  };
  const вПолосе = (узел) => {
    for (let род = узел.parentElement; род && род !== document.body; род = род.parentElement) {
      const стиль = getComputedStyle(род);
      const тянут = стиль.overflowX === 'auto' || стиль.overflowX === 'scroll' || стиль.overflow === 'auto' || стиль.overflow === 'scroll';
      if (тянут && род.scrollWidth > род.clientWidth + 1) return true;
    }
    return false;
  };
  const текстовыеУзлы = (корень) => {
    const обход = document.createTreeWalker(корень, NodeFilter.SHOW_TEXT);
    const список = [];
    for (let узел = обход.nextNode(); узел; узел = обход.nextNode()) {
      if (!узел.nodeValue.trim() || !узел.parentElement) continue;
      if (!узел.parentElement.getBoundingClientRect().width) continue;
      список.push(узел);
    }
    return список;
  };
  const охват = (узлы) => {
    let лево = Infinity, верх = Infinity, право = -Infinity, низ = -Infinity;
    const полосы = [];
    for (const узел of узлы) {
      const диапазон = document.createRange();
      диапазон.selectNodeContents(узел);
      for (const р of диапазон.getClientRects()) {
        if (!р.width || !р.height) continue;
        лево = Math.min(лево, р.left); верх = Math.min(верх, р.top);
        право = Math.max(право, р.right); низ = Math.max(низ, р.bottom);
        полосы.push({ top: р.top, bottom: р.bottom });
      }
    }
    // Строки = кластеры прямоугольников, перекрывающихся по вертикали больше чем на
    // половину высоты: два span рядом дают одну строку, перенос — две.
    полосы.sort((а, б) => а.top - б.top);
    let строк = 0, край = -Infinity;
    for (const полоса of полосы) {
      const высота = полоса.bottom - полоса.top;
      if (полоса.top >= край - высота * 0.5) { строк += 1; край = полоса.bottom; } else { край = Math.max(край, полоса.bottom); }
    }
    return { лево, право, верх, низ, строк };
  };

  const записи = [];
  const родители = new Map();
  for (const элемент of document.querySelectorAll('button, a[class*="btn"], [role="button"]')) {
    if (!этоКонтрол(элемент)) continue;
    const рамка = элемент.getBoundingClientRect();
    if (!рамка.width || !рамка.height) continue;
    const стиль = getComputedStyle(элемент);
    if (стиль.visibility === 'hidden' || стиль.display === 'none' || элемент.closest('[hidden]')) continue;
    const узлы = текстовыеУзлы(элемент);
    if (!узлы.length) continue;
    const подпись = охват(узлы);
    const родитель = элемент.parentElement;
    const рамкаМеста = родитель ? родитель.getBoundingClientRect() : null;
    if (!родители.has(родитель)) родители.set(родитель, родители.size);
    записи.push({
      ряд: родитель ? родители.get(родитель) : -1,
      вПотоке: стиль.position !== 'fixed' && стиль.position !== 'absolute',
      текст: узлы.map((у) => у.nodeValue.trim()).join(' ').replace(/\s+/g, ' ').slice(0, 60),
      селектор: элемент.tagName.toLowerCase() + (String(элемент.className || '').trim() ? '.' + String(элемент.className).trim().split(/\s+/).slice(0, 2).join('.') : ''),
      ширина: +рамка.width.toFixed(1),
      высота: +рамка.height.toFixed(1),
      верх: рамка.top,
      низ: рамка.bottom,
      врезка: {
        слева: +(подпись.лево - рамка.left).toFixed(1),
        справа: +(рамка.right - подпись.право).toFixed(1),
        сверху: +(подпись.верх - рамка.top).toFixed(1),
        снизу: +(рамка.bottom - подпись.низ).toFixed(1),
      },
      строк: подпись.строк,
      обрез: { горизонталь: элемент.scrollWidth - элемент.clientWidth, вертикаль: элемент.scrollHeight - элемент.clientHeight },
      стили: { padding: стиль.padding, белый: стиль.whiteSpace, минвысота: стиль.minHeight, шрифт: стиль.fontSize },
      полоса: вПолосе(элемент),
      ширеМеста: !!(родитель && рамкаМеста && рамка.width > рамкаМеста.width + 1 && стиль.position !== 'absolute' && стиль.position !== 'fixed'),
      разбросРяда: 0,
    });
  }

  // Ряд: контролы с общим предком, чьи рамки перекрываются по вертикали больше чем
  // на половину меньшей высоты. Кластеры склеиваем транзитивно (A рядом с B, B с C).
  const группы = new Map();
  for (const запись of записи) {
    if (!запись.вПотоке || запись.ряд < 0) continue;
    if (!группы.has(запись.ряд)) группы.set(запись.ряд, []);
    группы.get(запись.ряд).push(запись);
  }
  const рядом = (а, б) => {
    const высота = Math.min(а.высота, б.высота);
    if (!высота) return false;
    return (Math.min(а.низ, б.низ) - Math.max(а.верх, б.верх)) / высота >= 0.5;
  };
  for (const список of группы.values()) {
    if (список.length < 2) continue;
    const кластеры = [];
    for (const запись of список) {
      const подходящие = кластеры.filter((кластер) => кластер.some((член) => рядом(член, запись)));
      const новый = [запись, ...подходящие.flat()];
      for (const кластер of подходящие) кластеры.splice(кластеры.indexOf(кластер), 1);
      кластеры.push(новый);
    }
    for (const кластер of кластеры) {
      if (кластер.length < 2) continue;
      const высоты = кластер.map((х) => х.высота);
      const разброс = +(Math.max(...высоты) - Math.min(...высоты)).toFixed(1);
      for (const член of кластер) член.разбросРяда = Math.max(член.разбросРяда, разброс);
    }
  }
  return записи;
};

function вины(запись) {
  const список = [];
  for (const сторона of ['слева', 'справа', 'сверху', 'снизу']) {
    if (запись.врезка[сторона] < -РАЗРЯД) список.push(`слова вышли за рамку (${сторона}) на ${(-запись.врезка[сторона]).toFixed(1)}px`);
  }
  if (запись.строк === 1 && Math.min(запись.врезка.слева, запись.врезка.справа) < ВРЕЗКА) {
    список.push(`слова впритык к рамке: слева ${запись.врезка.слева}px, справа ${запись.врезка.справа}px`);
  }
  if (Math.min(запись.врезка.сверху, запись.врезка.снизу) < ВРЕЗКА) {
    список.push(`слова впритык к рамке по высоте: сверху ${запись.врезка.сверху}px, снизу ${запись.врезка.снизу}px при ${запись.строк} строках`);
  }
  if (запись.обрез.горизонталь > РАЗРЯД) список.push(`текст обрезан по горизонтали на ${запись.обрез.горизонталь}px`);
  if (запись.обрез.вертикаль > РАЗРЯД) список.push(`текст обрезан по вертикали на ${запись.обрез.вертикаль}px`);
  if (запись.ширеМеста && !запись.полоса) список.push(`кнопка шире своего контейнера (${запись.ширина}px)`);
  if (запись.разбросРяда > РАЗБРОС && !запись.полоса) список.push(`ряд неровный: высоты контролов отличаются на ${запись.разбросРяда}px`);
  return список;
}

const разбор = (запись) => `padding ${запись.стили.padding}, min-height ${запись.стили.минвысота}, `
  + `шрифт ${запись.стили.шрифт}, белый ${запись.стили.белый} | рамка ${запись.ширина}×${запись.высота}, `
  + `врезка С${запись.врезка.слева}/Ю${запись.врезка.справа}/В${запись.врезка.сверху}/Н${запись.врезка.снизу}`;

const дефекты = (витрина, где, записи) => записи.flatMap((запись) => {
  const список = вины(запись);
  return список.length ? [`${витрина} @${где} · ${запись.метка} → ${запись.селектор} «${запись.текст}»: ${список.join('; ')} | ${разбор(запись)}`] : [];
});

async function снять(page, маршруты, витрина, где) {
  const накопленные = [];
  for (const маршрут of маршруты) {
    await page.goto(маршрут.адрес, { waitUntil: 'networkidle' });
    await page.evaluate(() => document.fonts.ready);
    if (маршрут.раскрыть) await маршрут.раскрыть(page);
    const снято = await page.evaluate(ЗАМЕР);
    // Пустой замер выглядит в отчёте точь-в-точь как ровная вёрстка: ноль вин и ноль
    // контролов. Поэтому у каждого маршрута есть свой пол — он известен из состава
    // страницы, а не подогнан под результат.
    expect(снято.length, `${витрина} @${где} · ${маршрут.метка}: снято ${снято.length} контролов, ожидалось не меньше ${маршрут.минимум || 2} — страница не отдала вёрстку`).toBeGreaterThanOrEqual(маршрут.минимум || 2);
    for (const запись of снято) накопленные.push({ ...запись, метка: маршрут.метка });
    if (маршрут.раскрыть) await page.keyboard.press('Escape').catch(() => {});
  }
  expect(накопленные.length, `${витрина} @${где}: замер не снял контролы — страницы пустые`).toBeGreaterThan(50);
  return накопленные;
}

const ТОВАР = (catalog.products.find((товар) => товар.packs?.some((фасовка) => фасовка.price > 0)) || catalog.products[0]).id;

// Гидратацию ждём только на Next: у статической витрины обработчики навешаны
// inline-скриптом на DOMContentLoaded, и React-пропсов у её контролов нет никогда.
const открытьПлеерИсторий = (ждёмГидратацию) => async (page) => {
  const пузырёк = page.locator('.story-bubble').first();
  if (!(await пузырёк.isVisible().catch(() => false))) return;
  if (ждёмГидратацию) await готовККлику(пузырёк, 'пузырёк историй');
  await пузырёк.click();
  await page.waitForTimeout(400);
};

const открытьПанельСвязи = (селектор) => async (page) => {
  const кнопка = page.locator(селектор).first();
  if (!(await кнопка.isVisible().catch(() => false))) return;
  await кнопка.click().catch(() => {});
  await page.waitForTimeout(300);
};

for (const проход of [{ имя: 'проектная ширина', вьюпорт: null }, { имя: '320', вьюпорт: УЗКАЯ }]) {
  test(`next: подпись контрола не липнет к рамке, ряды одной высоты (${проход.имя})`, async ({ page, baseURL }, info) => {
    const адрес = `${baseURL}/catalog`;
    if (проход.вьюпорт) await page.setViewportSize(проход.вьюпорт);
    // Корзина и оформление живут на /cart, и пустая страница отличается от заполненной:
    // строки позиций, контролы количества и кнопка «Очистить корзину» появляются только с товаром.
    await page.goto(адрес, { waitUntil: 'networkidle' });
    const добавить = page.locator('.add-btn').first();
    await готовККлику(добавить, 'добавление из каталога');
    await добавить.click();
    const маршруты = [
      { адрес: `${baseURL}/`, метка: 'первый экран', минимум: 10, раскрыть: открытьПлеерИсторий(true) },
      { адрес, метка: 'каталог', минимум: 20 },
      { адрес: `${baseURL}/product/${ТОВАР}`, метка: 'страница товара', минимум: 3 },
      { адрес: `${baseURL}/about`, метка: 'наша лавка', минимум: 2, раскрыть: открытьПанельСвязи('[popovertarget="contact-panel"], .contact-link') },
      { адрес: `${baseURL}/cart`, метка: 'корзина и оформление', минимум: 5 },
    ];
    const плохие = дефекты('next', `${info.project.name}/${проход.имя}`, await снять(page, маршруты, 'next', `${info.project.name}/${проход.имя}`));
    expect(плохие, `кривые кнопки на next (${проход.имя}):\n${плохие.join('\n')}`).toEqual([]);
  });

  test(`витрина на Pages: подпись контрола не липнет к рамке, ряды одной высоты (${проход.имя})`, async ({ page }, info) => {
    const база = process.env.E2E_STATIC_URL;
    if (проход.вьюпорт) await page.setViewportSize(проход.вьюпорт);
    await page.goto(`${база}/index.html`, { waitUntil: 'networkidle' });
    const вкладки = await page.$$eval('.site-tabs button', (узлы) => узлы.map((у) => у.textContent.trim()));
    const маршруты = вкладки.map((имя) => ({
      адрес: `${база}/index.html`,
      минимум: /каталог/i.test(имя) ? 20 : 2,
      метка: имя,
      раскрыть: async (страница) => { await страница.locator('.site-tabs').getByText(имя, { exact: false }).first().click().catch(() => {}); },
    }));
    маршруты.unshift({ адрес: `${база}/index.html`, метка: 'первый экран', минимум: 10, раскрыть: открытьПлеерИсторий(false) });
    const открытьКорзину = async (страница) => {
      await страница.locator('.add-btn').first().click().catch(() => {});
      await открытьСтатичнуюКорзину(страница);
    };
    маршруты.push({ адрес: `${база}/index.html`, метка: 'шторка корзины', раскрыть: открытьКорзину });
    маршруты.push({ адрес: `${база}/index.html`, метка: 'панель связи', раскрыть: открытьПанельСвязи('[data-popover-target="contact-panel"], .contact-link') });
    const плохие = дефекты('static', `${info.project.name}/${проход.имя}`, await снять(page, маршруты, 'static', `${info.project.name}/${проход.имя}`));
    expect(плохие, `кривые кнопки на Pages (${проход.имя}):\n${плохие.join('\n')}`).toEqual([]);
  });
}
