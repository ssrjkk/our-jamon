// Числа в видимом тексте обязаны быть неразрывными.
// Обычный пробел внутри числа («2 000 г») и перед единицей («2000 г») — законное место переноса
// строки: на узком экране цифра разъезжается по двум строкам, «2» остаётся в конце одной,
// «000 г» начинается с другой. Выглядит такая разметка целиком корректно, поэтому глазами
// дефект не поймать — только кодами.
// Конвенцию задаёт не вкус, а рантайм: Intl.NumberFormat('ru-RU') вставляет в цены неразрывный
// разделитель тысяч, и единицы веса в коде уже приклеены к цифре тем же символом. Значит
// рукописная проза обязана печатать ровно тот же кодпоинт, что и форматированные цены, иначе
// на одном экране появляются две разные типографики чисел.
// Второе правило файла: латинская омоглифа внутри кириллического слова («молoко» с латинской
// o) неотличима глазами, но ломает поиск по странице и произношение экранного читателя.
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { root } = require('./helpers.cjs');

const NBSP = '\u00A0';  // сам неразрывный записан экранированием: невидимый символ в исходнике теста теряется при первом же редактировании

// Считаются только те куски, что реально доезжают до DOM: строковые литералы и JSX-текст.
// Комментарии и идентификаторы смешивают кириллицу с латиницей легально («Next-витрина»),
// и проверка их была бы машиной мусора. Вырезание комментариев сохраняет и длину, и переводы
// строк, поэтому позиция куска совпадает с позицией в исходнике и нарушение можно показать
// строкой, а не только подписью файла — иначе починка превращается в ручной поиск.
function кускиТекста(исходник) {
  const безКомментариев = исходник
    .replace(/\/\*[\s\S]*?\*\//g, (с) => с.replace(/[^\n]/g, ' '))
    .replace(/^[^\S\n]*\/\/[^\n]*/gm, (с) => с.replace(/[^\n]/g, ' '));
  const куски = [];
  // Экранирование (`\\u00A0`, `\\n`) обязано оставаться внутри куска. Прежний класс
  // `[^'\\\\]` обрывал литерал на первом же бэкспейсе, и строка, только что честно
  // починенная на неразрывный пробел, молча исчезала из корпуса — проверка продолжала
  // «зеленеть», уже ничего не видя.
  for (const m of безКомментариев.matchAll(/'((?:[^'\\]|\\.)*)'|"((?:[^"\\]|\\.)*)"|`((?:[^`\\]|\\.)*)`/g)) куски.push({ текст: m[1] ?? m[2] ?? m[3], позиция: m.index + 1, jsx: false });
  // JSX-текст — это то, что стоит сразу за закрывающей скобкой настоящего тега. Брать всё
  // между «>» и «<» нельзя: «weight > 30000) throw …» тоже начинается с «>», и обычный
  // оператор сравнения выдаёт фальшивый кусок с хвостом кода. Зато внутри самого тега надо
  // разрешить «=>»: иначе обработчик вида onClick={() => …} обрывает поиск открывающей
  // скобки, и текст за таким контролом (там живёт «{value} г») просто не попадает в корпус.
  // Закрывающий «<» следующего тега смотрим опережением, а не съедаем: иначе он становится
  // началом следующего тега только для регулярки, и текст `<p>Ошибка</p>` терялся целиком —
  // ровно тот случай, который проверка и должна ловить.
  for (const m of безКомментариев.matchAll(/<[a-zA-Z!/](?:[^<>]|=>)*>([^<>]+)(?=<)/g)) if (!m[1].startsWith('/')) куски.push({ текст: m[1], позиция: m.index + m[0].indexOf(m[1]), jsx: true });
  return куски;
}

const строкаИсходника = (исходник, позиция) => (исходник.slice(0, позиция).match(/\n/g)?.length ?? 0) + 1;

// Экранирование в исходнике — это и есть неразрывный пробел, а не опечатка (регистр `u00A0`
// в дереве разный, поэтому без учёта регистра). Интерполяцию (`${maxG} г`, `{min}–{max} г`)
// разворачиваем в цифру: по поведению она неотличима от числа. Перенос строки с отступом
// сворачивается в один пробел — именно так его увидит браузер, иначе многострочная проза
// «до\n      2 000 г» осталась бы невидимой.
// `&nbsp;` разворачивается только в JSX-тексте: там её честно декодирует React. В строковом
// литерале это не символ, а буквальные шесть знаков, уехавшие в DOM, — считать их нормой
// означало бы закрепить сломанный текст.
// То же рассуждение зеркально верно для `\u00A0`: внутри строки его разворачивает JS, а в
// JSX-тексте backslash — обычный символ, и покупатель читает «мес.» после буквального
// «u00A0». Разворачивать escape в JSX-тексте означало бы замазать дефект, который эта
// проверка и поставлена ловить, поэтому разворот разрешён только не-JSX кускам.
const кНормальномуВиду = (кусок, jsx) => (jsx ? кусок.replace(/&nbsp;/gi, NBSP) : кусок.replace(/\\u00A0/gi, NBSP))
  .replace(/[^\S\u00A0]+/g, ' ')
  .replace(/\$\{[^}]*\}|\{[^}]*\}/g, '1');

const корпус = [];
for (const dir of ['app', 'components', 'lib']) {
  for (const запись of fs.readdirSync(path.join(root, dir), { withFileTypes: true, recursive: true })) {
    if (!запись.isFile() || !/\.(?:tsx|ts)$/.test(запись.name)) continue;
    const файл = path.join(запись.parentPath, запись.name);
    const исходник = fs.readFileSync(файл, 'utf8');
    const относительный = path.relative(root, файл).replace(/\\/g, '/');
    for (const { текст, позиция, jsx } of кускиТекста(исходник)) {
      корпус.push({ метка: `${относительный}:${строкаИсходника(исходник, позиция)}`, кусок: кНормальномуВиду(текст, jsx) });
    }
  }
}

// Эталон берётся из того же Intl, которым витрина печатает цены, а не из догадки теста.
function эталонРазделителя() {
  const формат = new Intl.NumberFormat('ru-RU').format(1234567);
  const разделитель = /[0-9](.)[0-9]/u.exec(формат)?.[1];
  assert.ok(разделитель, `Intl ru-RU напечатал «${формат}» вообще без разделителя тысяч — правило пора переписывать по факту`);
  return разделитель;
}

const ЕДИНИЦЫ = '(?:г|кг|т|₽|руб\\.|шт|мес|сут|дн|лет|порц)';

// Возвращает позиции пробелов, которые стоят там, где должен быть эталонный неразрывный.
function лишниеПробелы(кусок, эталон, шаблон) {
  const нарушения = [];
  for (const m of кусок.matchAll(new RegExp(`(?<=\\d)(.)${шаблон}`, 'gu'))) {
    if (/\s/.test(m[1]) && m[1] !== эталон) нарушения.push(m.index);
  }
  return нарушения;
}
const междуТысячами = (кусок, эталон) => лишниеПробелы(кусок, эталон, '(?=\\d{3}(?!\\d))');
const передЕдиницей = (кусок, эталон) => лишниеПробелы(кусок, эталон, `(?=${ЕДИНИЦЫ}(?![\\p{L}]))`);

test('эталон конвенции: Intl ru-RU разделяет тысячи неразрывно', () => {
  const эталон = эталонРазделителя();
  assert.ok(/[\u00A0\u2009\u202F]/.test(эталон), `Intl ru-RU печатает разделитель тысяч как U+${эталон.charCodeAt(0).toString(16).toUpperCase()} — обычные пробелы в прозе больше не нарушение, правило надо пересмотреть`);
});

test('разделитель тысяч в видимом тексте совпадает с эталоном Intl', () => {
  const эталон = эталонРазделителя();
  const нарушения = [];
  for (const { метка, кусок } of корпус) {
    for (const позиция of междуТысячами(кусок, эталон)) {
      нарушения.push(`${метка} · …${кусок.slice(Math.max(0, позиция - 14), позиция + 14).replace(/\s+/g, ' ')}…`);
    }
  }
  assert.deepEqual(нарушения, [], `${нарушения.length} мест(а) пишут тысячи обычным пробелом, и число переносится:\n${нарушения.join('\n')}`);
});

test('перед единицей измерения стоит неразрывный пробел', () => {
  const эталон = эталонРазделителя();
  const нарушения = [];
  for (const { метка, кусок } of корпус) {
    for (const позиция of передЕдиницей(кусок, эталон)) {
      нарушения.push(`${метка} · …${кусок.slice(Math.max(0, позиция - 16), позиция + 14).replace(/\s+/g, ' ')}…`);
    }
  }
  assert.deepEqual(нарушения, [], `${нарушения.length} мест(а) клеят единицу обычным пробелом, и она уезжает на новую строку:\n${нарушения.join('\n')}`);
});

test('детекторы не пустые: заведомое нарушение поймано, заведомая норма — нет', () => {
  const эталон = эталонРазделителя();
  assert.deepEqual(междуТысячами('вес от 50 до 2 000 г', эталон).length, 1, 'детектор тысяч не видит заведомое нарушение — проверка была бы пустой');
  assert.deepEqual(передЕдиницей('отрез 2000 г', эталон).length, 1, 'детектор единиц не видит заведомое нарушение — проверка была бы пустой');
  assert.equal(междуТысячами(`вес от 50 до 2${эталон}000${эталон}г`, эталон).length, 0, 'детектор тысяч считает нарушением уже правильный неразрывный разделитель');
  assert.ok(корпус.length >= 400, `корпус видимого текста усох до ${корпус.length} кусков: экстрактор потерял файлы или литералы, и молчание тестов ничего не гарантирует`);
  // Дыра экстрактора видна только на эталонном исходнике: текст за инлайн-обработчиком с
  // «=>» обязан попасть в корпус, иначе целая категория кнопок проверяется молча.
  assert.ok(кускиТекста('<button onClick={() => { set(String(v)); }}>{v} г</button>').some((piece) => piece.текст === '{v} г'),
    'экстрактор JSX теряет текст контрола с инлайн-обработчиком — «{value} г» не проверяется');
  assert.ok(кускиТекста('<div>{bad && <p className="e">вес от 50 до 2 000 г.</p>}</div>').some((piece) => piece.текст.includes('2 000 г')),
    'экстрактор теряет текст, стоящий сразу после условного тега, — именно так выглядит ошибка про валидный вес');
  // Вырезание комментариев обязано сохранять длину и переводы: на нём держится номер строки.
  assert.equal(строкаИсходника('a\n// note\nb = \'2 000 г\';', 17), 3,
    'позиция куска больше не соответствует строке исходника — отчёт врёт, куда смотреть');
  // Литерал с экранированным символом обязан оставаться в корпусе: иначе починка на
  // «\\u00A0» сама себя вычёркивает из проверки, и следующая опечатка там же не всплывёт.
  assert.ok(кускиТекста("const s = 'a\\u00A0b 2 000 г';").some((piece) => piece.текст.includes('2 000')),
    'экстрактор теряет литералы с бэкспейсом — починенные строки исчезают из корпуса');
  assert.equal(кНормальномуВиду('от 50 до 2&nbsp;000&nbsp;г', true).includes(NBSP), true,
    'сущность в JSX-тексте не разворачивается: честная починка «&nbsp;» считалась бы нарушением');
  assert.equal(кНормальномуВиду('от 50 до 2&nbsp;000 г', false).includes('&nbsp;'), true,
    'сущность внутри строкового литерала развёрнута в неразрывный — а в DOM уехали бы шесть знаков');
  assert.equal(кНормальномуВиду('Шаг — 1\\u00A0мес.', true).includes('\\u00A0'), true,
    'escape в JSX-тексте развёрнут в неразрывный: буквально напечатанное покупателю «\\u00A0» перестало бы быть нарушением');
});

// Escape-последовательность в JSX-тексте не разворачивается ничем: React печатает её
// посимвольно, и покупатель читает «Шаг — 2\u00A0мес.» вместо «Шаг — 2 мес.». Линия
// «Шаг — {scale.step}\u00A0мес.» жила в панели выдержки ровно так, пока нормализация
// корпуса не перестала прощать escape там, где JS не участвует.
// Содержимое `{…}` вырезается с учётом вложенности: там escape законен, его разворачивает
// JS («{'\u00A0'}», «`${n}\u00A0мес.`», «'Культура\nнарезки'»), и считать его нарушением
// означало бы закрасить всю размеченную витрину.
function выраженияНадо(текст) {
  const маска = текст.split('');
  let глубина = 0;
  for (let i = 0; i < текст.length; i += 1) {
    if (текст[i] === '{') глубина += 1;
    else if (текст[i] === '}') глубина = Math.max(0, глубина - 1);
    if (глубина > 0 || текст[i] === '{' || текст[i] === '}') маска[i] = ' ';
  }
  return маска.join('');
}

test('в JSX-тексте нет escape-последовательностей: их печатает буквально', () => {
  const нарушения = [];
  let jsxКусков = 0;
  for (const dir of ['app', 'components', 'lib']) {
    for (const запись of fs.readdirSync(path.join(root, dir), { withFileTypes: true, recursive: true })) {
      if (!запись.isFile() || !/\.(?:tsx|ts)$/.test(запись.name)) continue;
      const файл = path.join(запись.parentPath, запись.name);
      const исходник = fs.readFileSync(файл, 'utf8');
      const относительный = path.relative(root, файл).replace(/\\/g, '/');
      for (const { текст, позиция, jsx } of кускиТекста(исходник)) {
        if (!jsx) continue;
        jsxКусков += 1;
        const m = /\\u[0-9a-fA-F]{4}|\\x[0-9a-fA-F]{2}|\\[nrtbf]/.exec(выраженияНадо(текст));
        if (m) нарушения.push(`${относительный}:${строкаИсходника(исходник, позиция)} · …${текст.slice(Math.max(0, m.index - 14), m.index + 16).replace(/\s+/g, ' ')}…`);
      }
    }
  }
  assert.ok(jsxКусков >= 300, `JSX-текста в корпусе всего ${jsxКусков} кусков: экстрактор потерял разметку, и молчание проверки ничего не стоит`);
  // Пара самопроверок: escape в голом тексте — нарушение, тот же escape в выражении — нет.
  assert.equal(/\\u00A0/.test(выраженияНадо('Шаг — 1\\u00A0мес.')), true, 'детектор escape не видит заведомое нарушение');
  assert.equal(/\\u00A0/.test(выраженияНадо("Шаг — {scale.step}{'\\u00A0'}мес.")), false, 'детектор escape считает нарушением законный литерал внутри {…}');
  assert.equal(/\\n/.test(выраженияНадо('{ok ? \'Культура\\nнарезки\' : заголовок}')), false, 'вырезание не держит вложенные фигурные скобки');
  assert.deepEqual(нарушения, [], `${нарушения.length} мест(а) печатают escape покупателю:\n${нарушения.join('\n')}`);
});

